-- 首次打分时的封袋全集（含当时的公开特征）：两版权重稽核共用同一批封袋与同一份特征，
-- 既不用当前在柜状态反推历史，也不受之后品类、主色、描述被改动的影响。
CREATE TABLE IF NOT EXISTS recall_snapshots (
    search_id bigint PRIMARY KEY REFERENCES search_slips(id),
    algorithm text NOT NULL,
    dimensions integer NOT NULL,
    category_weight real NOT NULL,
    color_weight real NOT NULL,
    compared integer NOT NULL CHECK (compared >= 0),
    captured_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS recall_snapshot_bags (
    search_id bigint NOT NULL REFERENCES recall_snapshots(search_id) ON DELETE CASCADE,
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    category text NOT NULL,
    color varchar(32) NOT NULL,
    description varchar(160) NOT NULL,
    train_no varchar(12) NOT NULL,
    PRIMARY KEY (search_id, seal_id)
);

-- 每一轮稽核在开始时冻结样本：开测后确认的交付不进入本轮，留给下一轮。
CREATE TABLE IF NOT EXISTS weight_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    baseline_weight real NOT NULL DEFAULT 2.0,
    variant_weight real NOT NULL DEFAULT 1.0,
    started_at timestamptz NOT NULL,
    created_by text NOT NULL REFERENCES staff(email),
    status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'complete'))
);

CREATE TABLE IF NOT EXISTS weight_audit_samples (
    audit_id bigint NOT NULL REFERENCES weight_audits(id) ON DELETE CASCADE,
    search_id bigint NOT NULL REFERENCES search_slips(id),
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    released_at timestamptz NOT NULL,
    has_snapshot boolean NOT NULL,
    PRIMARY KEY (audit_id, search_id)
);

-- (audit_id, search_id, variant) 唯一约束保证中断重试时同一张线索只计一次。
CREATE TABLE IF NOT EXISTS weight_audit_results (
    audit_id bigint NOT NULL,
    search_id bigint NOT NULL,
    variant text NOT NULL CHECK (variant IN ('baseline', 'variant')),
    true_rank integer CHECK (true_rank > 0),
    true_score real,
    compared integer NOT NULL CHECK (compared >= 0),
    hit boolean NOT NULL,
    computed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (audit_id, search_id, variant),
    FOREIGN KEY (audit_id, search_id) REFERENCES weight_audit_samples(audit_id, search_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS weight_audit_results_pending ON weight_audit_results (audit_id, search_id);
